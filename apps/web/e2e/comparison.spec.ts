import { expect, test } from '@playwright/test'

test('split comparison reports the same-coordinate acoustic change on a common scale', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('probe-value')).not.toContainText('—')
  await page.getByRole('button', { name:'Save as baseline' }).click()
  await page.getByTestId('door-toggle').click()
  await expect(page.getByTestId('comparison-split')).toBeEnabled()
  await page.getByTestId('comparison-split').click()
  await expect(page.getByTestId('comparison-panel')).toHaveAttribute('data-compatible','true')
  await expect(page.getByTestId('comparison-probe-delta')).toHaveText('6.0 dB')
  await expect(page.getByTestId('comparison-shared-scale')).toContainText('-36 to 0 dB')
  await expect(page.getByTestId('comparison-changes')).toContainText('hall-door')
  await expect(page.getByTestId('comparison-baseline-canvas')).toBeVisible()
  await expect(page.getByTestId('comparison-current-canvas')).toBeVisible()
  await page.screenshot({ path:'reports/screenshots/comparison.png',fullPage:true })
  await page.getByTestId('view-plan').click()
  await expect(page.getByTestId('comparison-panel')).not.toBeVisible()
  await expect(page.getByTestId('field-canvas')).toBeVisible()
})

test('radio split comparison uses dB deltas and explains a frequency mismatch', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('probe-value')).not.toContainText('—')
  await page.getByTestId('mode-radio').click()
  await expect(page.getByTestId('probe-value')).toContainText('dBm')
  await expect(page.getByTestId('field-quality')).toHaveAttribute('data-quality','balanced')
  await page.getByRole('button',{name:'Save as baseline'}).click()
  await page.getByTestId('door-toggle').click()
  await expect(page.getByTestId('comparison-split')).toBeEnabled()
  await page.getByTestId('comparison-split').click()
  await expect(page.getByTestId('comparison-probe-a')).toContainText('dBm')
  await expect(page.getByTestId('comparison-probe-delta')).toHaveText('2.0 dB')
  await page.getByTestId('frequency-select').selectOption('5000000000')
  await expect(page.getByTestId('field-quality')).toHaveAttribute('data-quality','balanced')
  await expect(page.getByTestId('comparison-split')).toBeDisabled()
  await expect(page.getByTestId('comparison-reason')).toContainText('Frequencies differ')
})

test('mobile comparison switches A/B without changing scales or overflowing', async ({ page }) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await expect(page.getByTestId('probe-value')).not.toContainText('—')
  await page.getByRole('button',{name:'Save as baseline'}).click()
  await page.getByTestId('door-toggle').click()
  await expect(page.getByTestId('comparison-split')).toBeEnabled()
  await page.getByTestId('comparison-split').click()
  await page.getByTestId('current-mobile-tab').click()
  await expect(page.getByTestId('comparison-current-canvas')).toBeVisible()
  await expect(page.getByTestId('comparison-baseline-canvas')).not.toBeVisible()
  await expect(page.getByTestId('comparison-shared-scale')).toContainText('-36 to 0 dB')
  const dimensions = await page.getByTestId('comparison-current-canvas').evaluate((canvas:HTMLCanvasElement) => ({width:canvas.width,css:canvas.getBoundingClientRect().width}))
  expect(dimensions.width).toBeGreaterThan(0)
  expect(dimensions.css).toBeGreaterThan(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391)
})

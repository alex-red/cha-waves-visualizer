import { expect, test, type Page } from '@playwright/test'

async function ready(page: Page) {
  await expect(page.getByTestId('solver-status')).not.toContainText('Calculating', { timeout: 15_000 })
  await expect(page.getByTestId('probe-value')).not.toContainText('—')
}

// The guided UI is a real workspace transition: readings, history and export
// must agree rather than only changing the story text.
test('guided home loading and interventions restore the previous workspace through undo', async ({ page }) => {
  await page.goto('/')
  await ready(page)
  const initial = await page.getByTestId('probe-value').innerText()
  await page.getByRole('button', { name: 'Save as baseline' }).click()
  await page.getByTestId('scenario-open').click()
  await page.getByTestId('scenario-select').selectOption('home-acoustics')
  await page.getByTestId('scenario-load').click()
  await page.keyboard.press('Escape')
  await ready(page)
  const home = await page.getByTestId('probe-value').innerText()
  expect(home).not.toBe(initial)
  await page.screenshot({ path: 'reports/screenshots/guided-home.png', fullPage: true })
  await page.getByTestId('view-cutaway').click()
  await expect(page.getByTestId('cutaway-canvas')).toHaveAttribute('data-backend', /webgpu|webgl/, { timeout: 20_000 })
  await expect(page.getByTestId('probe-value')).toHaveText(home)
  await page.screenshot({ path: 'reports/screenshots/guided-cutaway.png', fullPage: true })
  await page.getByTestId('view-plan').click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await ready(page)
  await expect(page.getByTestId('probe-value')).toHaveText(initial)
  await expect(page.getByRole('button', { name: 'Compare', exact: false })).toBeEnabled()
})


test('guided acoustic edits compute a 7 dB door effect and an unchanged off-path control', async ({ page }) => {
  await page.goto('/')
  await ready(page)
  await page.getByTestId('scenario-open').click()
  await page.getByTestId('scenario-load').click()
  await page.keyboard.press('Escape')
  await ready(page)
  const baseline = Number.parseFloat(await page.getByTestId('probe-value').innerText())
  await page.getByTestId('scenario-open').click()
  await page.getByTestId('scenario-apply').click()
  await expect(page.getByTestId('scenario-result')).toContainText('+7.0 dB')
  await page.keyboard.press('Escape')
  await ready(page)
  expect(Number.parseFloat(await page.getByTestId('probe-value').innerText()) - baseline).toBeCloseTo(7, 1)
  await page.getByTestId('scenario-open').click()
  await page.getByLabel('Select a guided change').selectOption('open-study-door-control')
  await page.getByTestId('scenario-apply').click()
  await expect(page.getByTestId('scenario-result')).toContainText('0.0 dB')
  await page.keyboard.press('Escape')
  await ready(page)
  expect(Number.parseFloat(await page.getByTestId('probe-value').innerText())).toBe(baseline)
})

test('guided RF frequency history restores the model and current reading', async ({ page }) => {
  await page.goto('/')
  await ready(page)
  const initial = await page.getByTestId('probe-value').innerText()
  await page.getByTestId('scenario-open').click()
  await page.getByTestId('scenario-select').selectOption('home-radio')
  await page.getByLabel('Select a guided change').selectOption('change-radio-frequency')
  await page.getByTestId('scenario-apply').click()
  await page.keyboard.press('Escape')
  await ready(page)
  const radio = await page.getByTestId('probe-value').innerText()
  await expect(page.getByTestId('frequency-select')).toHaveValue('5000000000')
  expect(radio).toContain('dBm')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await ready(page)
  await expect(page.getByTestId('probe-value')).toHaveText(initial)
  await expect(page.getByTestId('frequency-select')).toHaveValue('1000')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await ready(page)
  await expect(page.getByTestId('probe-value')).toHaveText(radio)
  await expect(page.getByTestId('frequency-select')).toHaveValue('5000000000')
  await expect(page.getByTestId('project-status')).toHaveAttribute('data-state', 'saved')
  await page.reload()
  await ready(page)
  await expect(page.getByTestId('probe-value')).toHaveText(radio)
})
